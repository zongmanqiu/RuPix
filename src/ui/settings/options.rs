//! 「选项」页：四张可折叠卡片 —— 看图 / 界面 / 窗口 / 系统。
//!
//! ★ 2026-10-17 审计第二轮的前置拆分：`ui/settings.rs`（2699 行）大到没法逐行精读，
//!   本文件是其中**一页/一窗**的纯搬动切片——不改行为、不改文案、不改版式。
//!   父模块 `settings` 留 `Handles`（信号句柄与差分同步）、窗口装配与页序常量。
//!
//! ★ 2026-11-13（m328）：四张卡按**右键菜单的组名与顺序**重排——
//!   看图 → 界面 → 窗口 → 系统。
//!   ① 「外观」改名「界面」：卡内六项与右键「界面 ▸」逐项同序（m262 起就焊着，
//!      这一轮只补名字）。叫「界面」而不是「视图」，是为了跟「画面 / 窗口」拉开：
//!      三者分别指 **UI 元素 / 图怎么被看 / 窗怎么存在**，不再都是"看见的东西"。
