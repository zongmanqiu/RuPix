//! 「选项」页：四张可折叠卡片 —— 外观 / 窗口 / 看图 / 系统。
//!
//! ★ 2026-10-17 审计第二轮的前置拆分：`ui/settings.rs`（2699 行）大到没法逐行精读，
//!   本文件是其中**一页/一窗**的纯搬动切片——不改行为、不改文案、不改版式。
//!   父模块 `settings` 留 `Handles`（信号句柄与差分同步）、窗口装配与页序常量。
//!
//! ★ 2026-11-04（m224）：原先 15 行平铺，是设置五页里唯一没有卡片的一页。现按
//!   「用户想调这件事的时候会去哪找」分成四组，卡片与快捷键 / 解码器 / 插件三页同款
//!   （[`section_card`]：标题色带 + 折叠箭头 + 正文）。**只重排，不增删任何一项**，
//!   ini 键、读写与即时生效时机一个都没动；四张卡默认全展开（展开态是会话态、不落盘）。
//!   组序从「看得见」到「看不见」：外观 → 窗口 → 看图 → 系统。
//!   ★ m266：归属按「用户会去哪找」而不是「代码跑在哪一层」——图片预读改的是
//!   翻页 / 换图怎么被看到，从系统卡挪进看图卡；系统卡剩下的
//!   才是真正不看图时的事（联网来源、系统认不认我们）。
//!   ★ m288：第四张卡「系统与网络」改名「系统」（用户口径：卡里只剩「下载源」一项
//!   带"网"字，而它本质是"从哪拿东西"，不是网络设置；改的只是标签，id 仍是
//!   `options.system`，老用户的折叠状态不受影响）。
//!
//! ★ m273：第三张卡「看图与操作」改名「看图」，卡片 id 仍是 `options.browse`
//!   （id 一改老用户的折叠状态就失效，见 `Card::id` 的注释；改的只是给人看的标签）。
//!   用户 m273 的原话是「窗口和看图都是窗口相关，好像可以合并」——**没有合并**，
//!   理由是高度：窗口 6 项 + 看图 5 项合起来 11 行，卡高 36 + 8 + 11×40 = 484dp，
//!   而设置窗客户区只有 480（不可缩放），正文可视高 464 —— 一张卡比整页还高，
//!   卡头卡尾永远不能同屏，折叠它等于折叠整页。合并只省下 52dp 滚动量（960 → 908）。
//!   用户真正的痛点是**卡内项序**，所以这一轮只重排、不合并（见两个 body 的开头）。
use super::*;

/// Options 页：四张卡按内容长短堆叠，整页只有最外层这一条滚动条。
///
/// 本页所有项都即时生效（m54）：窗口置顶 / 窗口大小 / 固定尺寸由 runtime 差分
/// 推给当前窗口，不再需要「下次启动生效」的尾巴。
///
/// `config` 只给「文件关联」的入口用（m314）：那个窗要读写 `assoc_exts` 勾选表，
/// 打开时按它预勾选、应用时写回。其余各项都走 `Handles` 里的信号。
pub fn options_page(h: &Handles, config: Rc<RefCell<Config>>) -> Element {
    Element::scroll()
        .fill()
        .padding_xy(16, PAGE_TOP_MARGIN)
        .child(
            Element::col()
                .fill()
                .spacing(GAP)
                .child(section_card("外观", h.card_appearance, appearance_body(h)))
                .child(section_card("窗口", h.card_window, window_body(h)))
                .child(section_card("看图", h.card_browse, browse_body(h)))
                .child(section_card("系统", h.card_system, system_body(h, config))),
        )
}

/// 「外观」：颜色与可见元素长什么样。六项全是看图窗口的观感，不改图片像素。
///
/// ★ m262 起项序与右键「外观 ▸」一致（显隐四件在前、整窗观感两件在后），
///   顺序接线由 `canvas.rs` 里的源码级钉子看着，改一边就会红。
///   m263 把「显示操作按钮」提到组首：它是这组里最常切的一颗（用户实机口径），
///   组内其余相对次序不变，分组仍是显隐四件 → 整窗观感两件。
///
/// ★ 归属判据（m246）：改「画面上出现什么 / 长什么样」→ 本卡 + 右键「外观 ▸」；
///   改「窗口或进程以什么方式存在」→ 下一张「窗口」卡，不进右键外观菜单。
fn appearance_body(h: &Handles) -> Element {
    Element::col()
        .fill()
        .spacing(0)
        // ★ m262：项序**照抄右键「外观 ▸」**（显隐四件 → 整窗观感两件）。
        //   右键是「正盯着图顺手切」的场景，高频开关必须靠上；这里跟着排，用户不用重学。
        // ★ m263：显示操作按钮提到组首（这组里最常切的一颗），两边一起挪。
        // ini 键：show_toolbar_buttons（m245）。关掉 = 浮条只留信息并水平居中；
        // 按钮对应的操作在右键「操作 ▸」里全都在，信息没有别的载体。
        // 同一个开关也在右键「外观 ▸」里，两处都写同一份 Config。
        .child(check_row("显示操作按钮", h.show_toolbar_buttons))
        // ini 键：minimal_mode（即时生效：runtime 差分推给当前窗口，m51-D）
        .child(check_row("极简模式", h.minimal_mode))
        // ini 键：checker（即时生效：runtime 每帧把配置推给当前窗口，m53-L）
        .child(check_row("棋盘格背景", h.checker))
        // ini 键：filmstrip + filmstrip_left（m262 合成三选一：关闭 / 下方 / 左侧）。
        // 选位置必然开条 ⇒「勾了左侧却没开条」这个死状态从入口上就产生不了；
        // 两个 bool 仍由 Handles::sync 折写，配置正本没动。关条时选的边留着，
        // 快捷键 T 再开会回到那边。标签与档位与右键共用 FILMSTRIP_POS。
        .child(choice_row(
            "缩略图条",
            FILMSTRIP_POS.iter().map(|s| (*s).to_string()).collect(),
            h.filmstrip_pos,
        ))
        // ini 键：ui_theme（0 深色 / 1 浅色）。**只影响看图窗口**——浮层胶囊、
        // 缩略图条、棋盘格、空窗底与中央提示文字；设置页、属性窗、对话框
        // 永远是浅底深字那一套（2026-11-02 用户口径）。标签 m223 起只写「主题色」，
        // 作用域没跟着变。换下拉当场生效：config 写回后 runtime 下一帧换令牌并重绘。
        .child(option_row(
            "主题色",
            Element::dropdown(
                UiTheme::ALL.iter().map(|t| t.label().to_string()).collect(),
                h.ui_theme,
            )
            .width(CONTROL_GROUP_W),
        ))
        // ini 键：opacity（0.2 ~ 1.0）。滑块 + 只读数值列，另有右键菜单十档与快捷键 ±
        // 两条入口；数值列不做输入框（刷新时会把用户敲到一半的值顶回去）。
        .child(slider_row("窗口不透明度", h.opacity, h.opacity_label))
}

/// 「窗口」：窗口／进程以什么方式存在——开成多大、要不要壳、z 序、关窗去向、能否开第二扇。
///
/// ★ m273 项序（用户：「窗口和看图都是窗口相关，好像可以合并」）。不合并的理由见文件头；
///   卡内分**两段**：`开成多大`（尺寸两根）→ `这扇窗怎么存在`（四条勾选）。
///   段内控件重量递减：下拉 / 输入在上、勾选在下，右列由"要读一眼"过渡到"点一下就完"。
///
/// ★ m273 修掉一处回归：m269 往「启动窗口」与「窗口尺寸」之间插了「无边框」，把它们
///   劈开了——而这两行是 m168 特意改名并写死"必须同组"的（一个选档、一个填宽高），
///   m272 又刚给下面那行加了"只有固定档才亮"的置灰：选完全屏往下看，隔着一行才发现
///   它灰了，因果是断的。现在两者紧挨，选档 → 置灰一眼看得见。
///
/// ★ m273「无边框」为什么没进「外观」卡（用户点名问过）：它是外观卡四颗的**总闸**——
///   一开，`极简模式`（`show_title` 的 `!bl`）、`显示操作按钮`（`show_toolbar` 的 `!bl`）、
///   `缩略图条`（`canvas` 的 `strip_on` 里那个 `!chrome::borderless()`）、`棋盘格背景`
///   （底色那圈 `if !chrome::borderless()`）全部作废。总闸和四个被它关掉的东西并排摆，
///   用户会撞上"我明明勾着缩略图条"——那是同卡内兄弟相残。
///   它改的也不止长相：chrome 的命中测试在 `borderless()` 时整段 `return None`、
///   画布左键拖动的分工跟着改（m272 整块画面当标题栏），窗口结构一起动；
///   外观卡其余六项一个都不碰这些。
///   另有一笔对称性代价：外观卡项序与右键「外观 ▸」逐项焊死
///   （`appearance_order_matches_between_settings_and_menu`），塞一个右键里没有的项，
///   要么把大动作放进右键（误点一下整个壳没了），要么承认这条轴断了。
fn window_body(h: &Handles) -> Element {
    Element::col()
        .fill()
        .spacing(0)
        // ── 第一段：开成多大 ──
        // ini 键：init_window（窗口尺寸三档：固定 / 全屏 / 图片尺寸）。
        // 前两档图片恒**适应窗口**，第三档反过来贴图片原始像素（翻页也跟着变）；
        // 具体宽高在紧挨着的下一行填，**只对固定档生效**——另外两档那一行是灰的。
        .child(option_row(
            "启动窗口",
            Element::dropdown(
                InitWindow::ALL
                    .iter()
                    .map(|w| w.label().to_string())
                    .collect(),
                h.init_win,
            )
            .width(CONTROL_GROUP_W),
        ))
        // ini 键：window_w / window_h（改下拉/文本框当场改窗；
        // 文本框等输入稳定 ~0.6s 再下发，避免打到一半被 clamp 成中间值）
        //
        // ★ m272：这两格**只对「固定尺寸」档有意义**——全屏由显示器决定、图片尺寸由
        //   图片决定，那两档下改了也不生效（按得住"用户以为是坏的"的最好办法是当场置灰）。
        //   置灰而不是隐藏：隐藏会让整张卡的高度随下拉跳、用户还会以为这一项被删了；
        //   `enabled_when` 沿父链禁用，标签与输入框一起降到 `text_disabled`。
        //   态的变化不用手动标脏：`layout_signature` 把 `own_enabled()`（含本闭包）折进
        //   签名，下拉选完值一交互就自动升整窗重绘。
        // ★ m273：紧挨「启动窗口」——m269 插队插坏过一次，见函数头两条 ★。
        .child(
            option_row(
                "窗口尺寸 (宽, 高)",
                Element::text_input(h.win_size, "800, 600").width(CONTROL_GROUP_W),
            )
            .enabled_when({
                let iw = h.init_win;
                move || InitWindow::from_ui_index(iw.get()) == InitWindow::Fixed
            }),
        )
        // ── 第二段：这扇窗怎么存在 ──
        // ini 键：borderless（m269）。与上面两条**正交**：这一项只决定 chrome 画不画
        // （标题栏 / 操作按钮 / 信息条 / 缩略图条 / 底色全隐，图片透明区透出桌面），
        // 三档尺寸都能配它。
        // ★ 鼠标不穿透：右键 / 快捷键 / 锁定 / 置顶 / 缩放全在（这正是它与
        // 「空格预览」的分界：那边是极致阉割 + 穿透）。
        .child(check_row("无边框", h.borderless))
        // ini 键：stay_on_top（改勾选当场翻转当前窗口的置顶）
        .child(check_row("窗口置顶", h.stay))
        // ini 键：close_to_tray（勾上即生效：托盘图标当场出现、关窗转为隐藏）
        .child(check_row("最小化到托盘", h.to_tray))
        // ini 键：allow_multiple（多开）。勾上后再双击图片，在同一进程里新开
        // 一扇窗口——进程与托盘始终只有一个。
        // 关闭时维持单窗口：双击另一张图会把 argv 转发到已有窗口、就地换图。
        .child(check_row("允许多开", h.allow_multiple))
}

/// 「看图」：图怎么被看、手怎么动、切下一张时看到什么（m273 前叫「看图与操作」）。
///
/// ★ m266：「图片预读」住这里。它改的不是「后台怎么跑」，而是**翻页 / 换图怎么被
///   看到**（连翻靠邻图、点条远跳靠那一屏），和「适应长图」「幻灯片间隔」同类；
///   m224 按实现层次把它塞进「系统与网络」是历史惯性。
/// ★ m273 项序：前四条**全是勾选**（看 / 拖 / 起 / 备），最后一行是唯一带数值的参数。
///   上一版的「幻灯片间隔」夹在「空格预览」和「图片预读」中间，把四行勾选的节奏
///   打了个缺口——数值型行收尾，卡里就只剩一种形态。
///   「空格预览」排在第三不是随手：它是本卡唯一越界到整个系统的一项（全局低级钩子，
///   在资源管理器里按空格就起窗），放在"看 → 拖"之后、"预备"之前，是"从眼前到后台"
///   这条斜坡上的自然一格。
fn browse_body(h: &Handles) -> Element {
    Element::col()
        .fill()
        .spacing(0)
        .child(check_row("适应长图", h.long_fit))
        // ini 键：drag_image（默认勾上）。勾着 = 画布里按住左键只平移图片、窗口不动，
        // 移动窗口交给**顶部标题栏**那一条；图比窗口小也拖得动，图边还能越过窗口边
        // （永远留 24dp 在画面里，图拖不丢）。
        // 取消勾选 = 回到旧分工：任意位置左键拖都拖窗口，平移改用 Ctrl+左键 / 中键 / 鸟瞰图。
        // 名字只说"左键"：中键与 Ctrl+左键一直能拖图，这个开关管的确实是左键那一路。
        // 同一个开关也在右键菜单的开关区（「极简模式 / 缩略图条」那一组）。
        .child(check_row("左键拖图", h.drag_image))
        // ini 键：space_preview（全局空格监听，低级钩子、从不吞键，作用于整个
        // 系统——与快捷键页的看图窗口内键位不同源；16ms 轮询差分装/摘钩，见
        // platform::spacehook）。★ 本组里唯一越界的：它不只管看图窗口，
        // 归本组是取「想找它的时候会去哪」的最大公约数。
        .child(check_row("空格看图", h.space_preview))
        // ★ m273：从卡尾上移一格，紧跟「空格看图」——四条勾选连排（看 → 拖 → 起 → 备），
        // 唯一带数值的「幻灯片间隔」收尾；上一版两行顺序反着，数值行夹在中间，
        // 把勾选与勾选之间的连读打断了。
        // ★ m266：从「系统与网络」挪来。ini 键：prefetch（默认勾上）。
        // **图片预读 = 邻图 ±N + 缩略图条可见的那一屏**：前者接键盘 / 浮条的
        // 连续翻页，后者接点格子远跳（m265）。N 由 ini `prefetch_depth` 管（默认 3），
        // **这一页刻意不摆输入框**——开关给用户，参数留给高级用户手改 ini（m281）。
        // 连续翻页，后者接点格子远跳（m265 之后条是独立滚动列表，当前图可以
        // 不在视野里，所以远跳的目标只能从条那一屏取）。后台解的全是**视口档**，
        // 与图片本身多大无关；下注集合按份数闸封顶、驻留由 256 MiB 字节闸封顶，
        // 都不随目录张数增长。关掉它，每次切图都要现场解码
        // （实测大图 130–260 ms，慢格式可到 1 s 以上）。
        .child(check_row("图片预读", h.prefetch))
        // ini 键：slide_interval（幻灯片每张停留秒数。整数输入框而不是四档下拉——
        // 秒数本来就是一条整数轴，压成档位反而给不出 4 秒、8 秒这种要的值。
        // 越界由 `clamp_slide_interval` 夹进 1..=600，打到一半的中间态不改配置）
        // ★ m273：本卡唯一不是勾选的行，**收在末尾**（见函数头）。
        .child(option_row(
            "幻灯片间隔 (秒)",
            Element::text_input(h.slide_secs, "3").width(CONTROL_GROUP_W),
        ))
}

/// 「系统」：不看图时的事——从哪拉东西、系统认不认我们。
///
/// m288 起标签从「系统与网络」收成「系统」：卡里唯一的联网项是「下载源」，而它问的是
/// "从哪拿东西"，不是"网络怎么配"；另一项「文件关联」是纯系统层。id 仍是
/// `options.system`（改 id 会让老用户的折叠状态失效，见 `Card::id`）。
/// ★ m266：图片预读已挪进「看图」卡（它改的是切图怎么被看到，不是后台层次）；
///   这一卡只剩两项，m244 加的文件关联是独立窗（ini 没有它的键——关联态住注册表，
///   修宪唯一例外）。
fn system_body(h: &Handles, config: Rc<RefCell<Config>>) -> Element {
    Element::col()
        .fill()
        .spacing(0)
        // ini 键：download_source（联网来源：解码器清单 / 插件清单 / 将来的软件本体更新
        // **共用这一个**）。2026-10-30 用户口径：一个用户机器的网络是固定的，所以只该有
        // 一个开关——两张下载卡左侧的下拉已撤，跟着这里走。
        .child(option_row(
            "下载源",
            Element::dropdown(
                crate::core::config::SourceId::ALL
                    .iter()
                    .map(|s| s.label().to_string())
                    .collect(),
                h.download_source,
            )
            .width(CONTROL_GROUP_W),
        ))
        // 文件关联（m244 建窗；m314 起勾选持久、m315 起自愈 opt-in）：独立窗。
        // 勾选落 ini（ini 键：assoc_exts），点「应用」写一次；「自动维护」是窗内
        // 另一颗开关（ini 键：assoc_heal，**默认关**），开了才有定时核对。这里只给入口。
        .child(option_row(
            "文件关联",
            super::rows::btn("管理…").on_click(move |ctx| {
                super::super::association::show(ctx, config.clone());
            }),
        ))
}
